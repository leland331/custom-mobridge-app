import hashlib
import struct
import zlib

import pytest

from mobridge import boots, commands, fif
from mobridge.commands import Access
from mobridge.framing import FramingUnknown, TextFramer, UnconfirmedMdiFramer
from mobridge.message import MdiMessage, encode_number
from mobridge.safety import Policy, SafetyError, classify_console


def make_fif(body=b'\xad' * 1000, product=0x202C, version=0x00020B08, flash_off=0x60000, pre_len=0x60, corrupt=False):
    entry = hashlib.md5(body).digest() + struct.pack('>IIII', product, version, flash_off, len(body))
    hdr = b'\xd3\x8b\xa6\x2c' + struct.pack('>II', 1, 1) + b'\0' * 16 + hashlib.md5(entry).digest() + entry
    z = zlib.compress(body + (b'x' if corrupt else b''))
    return b'{"DSPNV_VERS":210}\n\n Generated by imgtool'.ljust(pre_len, b'\0') + hdr + z


@pytest.mark.parametrize('pre_len', [0x48, 0x60])   # 2.0.0 and 2.11.x layouts
def test_fif_parses_both_layouts(pre_len):
    i = fif.parse(make_fif(pre_len=pre_len))
    assert i.intact and i.magic_offset == pre_len and i.version_str == '2.11.8'
    assert i.preamble_json == {'DSPNV_VERS': 210}
    assert fif.flash_problems(i) == []


def test_fif_rejections():
    assert any('MD5' in p for p in fif.flash_problems(fif.parse(make_fif(corrupt=True))))
    assert any('bootblock' in p for p in fif.flash_problems(fif.parse(make_fif(flash_off=0))))
    assert any('product' in p for p in fif.flash_problems(fif.parse(make_fif(product=0x2019))))
    with pytest.raises(fif.FifError):
        fif.parse(b'nope' * 100)


def test_message_str_matches_app_log_format():
    assert str(MdiMessage(0x100, 0x22, 1, 0xC04, 2, b'abc')) == 'MSG:0100.22.01.c04.2.(3)'
    with pytest.raises(ValueError, match='Width Out of Range'):
        encode_number(1, 9)


def test_console_safety():
    assert classify_console('nvm list') is Access.READ
    assert classify_console('spiflash read 0x60000') is Access.READ
    assert classify_console('spiflash erase 0x70000 0x1000') is Access.DESTRUCTIVE
    assert classify_console('something new') is Access.WRITE
    for bad in ('spiflash erase 0x0 0x1000', 'hw spiflash write 0x5f000 0x2000', 'spiflash write 4096 1'):
        with pytest.raises(SafetyError, match='bootblock'):
            classify_console(bad)
    p = Policy.read_only()
    p.check_console('nvm list')
    with pytest.raises(SafetyError):
        p.check_console('nvm clear')
    with pytest.raises(SafetyError):   # bootblock is blocked even with everything allowed
        Policy.allow(*Access).check_console('spiflash erase 0 16')


def test_catalog_is_conservative():
    assert commands.get('FactoryReset').access is Access.DESTRUCTIVE
    assert commands.get('FlashFile').access is Access.WRITE
    assert all(c.opcode is None for c in commands.COMMANDS.values())


def test_default_framer_never_encodes():
    with pytest.raises(FramingUnknown):
        UnconfirmedMdiFramer().encode(MdiMessage())


def test_text_framer_splits_lines():
    tf = TextFramer()
    assert [f.text for f in tf.feed(b'READY\r\nPROG')] == ['READY']
    assert [f.text for f in tf.feed(b'RESS 5\n')] == ['PROGRESS 5']


def test_boots_line_parser():
    st = boots.BootsStatus()
    for ln in ('READY', 'OPENING', 'MD5 CHECK', 'PROGRAMMING', 'PROGRESS 40 : 400/1000'):
        boots.parse_line(ln, st)
    assert (st.state, st.percent, st.done, st.total) == ('progress', 40, 400, 1000)
    boots.parse_line('PROGRESS 100 : 1000/1000', st)
    assert st.finished and st.state == 'complete'
    assert boots.parse_line('ERROR: bad md5', boots.BootsStatus()).state == 'error'


def test_flash_dry_run_sends_nothing(tmp_path):
    p = tmp_path / 'img.fif'; p.write_bytes(make_fif(product=0x2046))  # 0x202c is refused (MDI path)
    st = boots.BootsFlasher(None, Policy.read_only(), log=lambda s: None).flash(str(p))
    assert st.state == 'idle'


def test_flash_execute_needs_write_policy(tmp_path):
    from fakes import ScriptedTransport
    p = tmp_path / 'img.fif'; p.write_bytes(make_fif(product=0x2046))
    t = ScriptedTransport()
    with pytest.raises(SafetyError):
        boots.BootsFlasher(t, Policy.read_only(), log=lambda s: None).flash(str(p), execute=True)
    assert t.sent == b''
